"""Document I/O: a technical capability, deliberately domain-neutral.

The core can read text out of documents and produce simple PDFs. What a
document *means* (an invoice, an application, an order) is template-layer
business and never encoded here.

Reading: the main path is digital PDFs with a text layer (pdfplumber, MIT).
Scans and photos go through OCR (ADR-0028): :class:`TesseractOcr` drives
the locally installed ``tesseract`` binary (Apache-2.0, reached as a
subprocess - compute-heavy work stays native, docs/DEPLOYMENT.md), and
:class:`EscalatingOcr` hands a page to a vision model when the local
result is weak *and* the caller has decided that the page's data class
and the legal space allow it. :class:`UnavailableOcr` is the honest
default that reports the capability as missing instead of pretending.

Writing: :func:`create_pdf` produces a plain text-based PDF (reportlab,
BSD). Enough for receipts/confirmations generated by templates; layout
sophistication can grow behind the same function.

License guardrail (ADR-0009): only permissive dependencies - PyMuPDF (AGPL)
stays out until the license decision is made.
"""

from __future__ import annotations

import io
import json
import logging
import shutil
import subprocess
import tempfile
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

import pdfplumber
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

from .formats import HTML_TYPES, OFFICE_TYPES, FormatError, html_page, office_text
from .transcribe import (
    AUDIO_TYPES,
    VIDEO_TYPES,
    Ffmpeg,
    FrameDescriber,
    Transcriber,
    TranscriptionError,
    UnavailableTranscriber,
    transcribe_video,
)

log = logging.getLogger("aitmation.document")

IMAGE_TYPES = {
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".gif": "image/gif",
    ".bmp": "image/bmp",
    ".tif": "image/tiff",
    ".tiff": "image/tiff",
}
"""Photos and scans the intake accepts as documents (ADR-0028)."""

RENDER_DPI = 200

CACHE_SUFFIX = ".extracted.json"
"""Expensive extractions (OCR, transcription) are cached next to the file
so a chain of agent steps pays once (ADR-0030)."""


@dataclass(frozen=True)
class ExtractedText:
    text: str
    page_count: int
    method: str  # "text_layer" | "plain_text" | "ocr:<engine>"

    @property
    def is_empty(self) -> bool:
        return not self.text.strip()


class DocumentError(RuntimeError):
    """The document could not be read or produced."""


@dataclass(frozen=True)
class OcrResult:
    text: str
    confidence: float | None  # mean word confidence 0..1 where the engine reports one
    engine: str


class OcrEngine(Protocol):
    """Interface to an OCR capability outside this process."""

    name: str

    def recognize(self, path: Path) -> str:
        """Return the recognized text for a scanned document."""
        ...


class UnavailableOcr:
    """Default OCR engine: reports the missing capability loudly."""

    name = "unavailable"

    def recognize(self, path: Path) -> str:
        raise DocumentError(
            f"{path.name}: no text layer and no OCR engine configured;"
            " install Tesseract (see docs/DEPLOYMENT.md) or release a vision model"
        )


def page_images(path: str | Path) -> list[tuple[bytes, str]]:
    """The document as page images (bytes, media type): an image file as
    itself, a PDF rendered page by page. Basis for OCR and vision."""
    path = Path(path)
    suffix = path.suffix.lower()
    if suffix in IMAGE_TYPES:
        return [(path.read_bytes(), IMAGE_TYPES[suffix])]
    if suffix != ".pdf":
        raise DocumentError(f"{path.name}: not an image or PDF")
    out: list[tuple[bytes, str]] = []
    try:
        with pdfplumber.open(path) as pdf:
            for page in pdf.pages:
                image = page.to_image(resolution=RENDER_DPI).original
                buffer = io.BytesIO()
                image.convert("RGB").save(buffer, format="PNG")
                out.append((buffer.getvalue(), "image/png"))
    except Exception as exc:
        raise DocumentError(f"{path.name}: cannot render PDF pages: {exc}") from exc
    return out


class TesseractOcr:
    """OCR through the locally installed ``tesseract`` binary.

    Nothing leaves the machine. The binary is found on PATH or named
    explicitly (``AITMATION_TESSERACT_PATH``); languages are Tesseract
    codes joined with ``+`` (default German, French, Italian, English -
    the product's four, ADR-0022). Word confidences from the TSV output
    give the mean confidence the escalation decides on.
    """

    name = "tesseract"

    def __init__(
        self,
        binary: str | None = None,
        languages: str = "deu+fra+ita+eng",
        *,
        runner: Callable[[list[str], bytes | None], subprocess.CompletedProcess] | None = None,
    ) -> None:
        self.binary = binary or shutil.which("tesseract") or "tesseract"
        self.languages = languages
        self._run = runner or self._default_run

    @staticmethod
    def _default_run(args: list[str], stdin: bytes | None) -> subprocess.CompletedProcess:
        return subprocess.run(args, input=stdin, capture_output=True, timeout=300, check=False)

    def available(self) -> bool:
        return shutil.which(self.binary) is not None or Path(self.binary).is_file()

    def installed_languages(self) -> list[str]:
        try:
            result = self._run([self.binary, "--list-langs"], None)
        except (OSError, subprocess.SubprocessError) as exc:
            raise DocumentError(f"tesseract not usable: {exc}") from exc
        lines = (result.stdout or b"").decode("utf-8", "replace").splitlines()
        return [line.strip() for line in lines[1:] if line.strip()]

    def recognize(self, path: Path) -> str:
        return self.recognize_detailed(path).text

    def recognize_detailed(self, path: str | Path) -> OcrResult:
        """Every page through Tesseract's TSV mode: text plus mean word
        confidence (0..1). A missing binary is a DocumentError, not a crash."""
        texts: list[str] = []
        confidences: list[float] = []
        for image, _media in page_images(path):
            text, conf = self._page(image)
            texts.append(text)
            confidences.extend(conf)
        mean = sum(confidences) / len(confidences) / 100.0 if confidences else None
        text = "\n\n".join(t for t in texts if t).strip()
        return OcrResult(text=text, confidence=mean, engine=self.name)

    def _page(self, image: bytes) -> tuple[str, list[float]]:
        with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as handle:
            handle.write(image)
            tmp = Path(handle.name)
        try:
            args = [self.binary, str(tmp), "stdout", "-l", self.languages, "--psm", "3", "tsv"]
            try:
                result = self._run(args, None)
            except (OSError, subprocess.SubprocessError) as exc:
                raise DocumentError(f"tesseract failed: {exc}") from exc
            if result.returncode != 0:
                detail = (result.stderr or b"").decode("utf-8", "replace").strip()[-300:]
                raise DocumentError(f"tesseract exited with {result.returncode}: {detail}")
            return _parse_tsv((result.stdout or b"").decode("utf-8", "replace"))
        finally:
            tmp.unlink(missing_ok=True)


def _parse_tsv(tsv: str) -> tuple[str, list[float]]:
    """Tesseract TSV → text with line breaks and the word confidences."""
    lines: list[str] = []
    current: list[str] = []
    current_key: tuple[str, str, str] | None = None
    confidences: list[float] = []
    for row in tsv.splitlines()[1:]:
        cols = row.split("\t")
        if len(cols) < 12:
            continue
        key = (cols[1], cols[2], cols[4])  # page, block, line
        word = cols[11].strip()
        try:
            conf = float(cols[10])
        except ValueError:
            conf = -1.0
        if key != current_key:
            if current:
                lines.append(" ".join(current))
            current, current_key = [], key
        if word:
            current.append(word)
            if conf >= 0:
                confidences.append(conf)
    if current:
        lines.append(" ".join(current))
    return "\n".join(lines), confidences


VisionTranscriber = Callable[[bytes, str], tuple[str, float | None]]
"""(image bytes, media type) → (transcript, confidence); provided by the
runtime from a released vision model when the data class allows it."""


class EscalatingOcr:
    """Local OCR first, a vision model only when needed and allowed.

    ``vision`` is None when the caller decided the page may not go to a
    model (data class above the model's clearance, legal space, or no
    vision model released) - then the local result stands, however weak,
    and a missing local engine is an honest error (ADR-0028).
    """

    name = "escalating"

    def __init__(
        self,
        local: TesseractOcr | None,
        vision: VisionTranscriber | None = None,
        *,
        min_confidence: float = 0.6,
        min_chars: int = 20,
    ) -> None:
        self.local = local
        self.vision = vision
        self.min_confidence = min_confidence
        self.min_chars = min_chars
        self.last_engine = "none"

    def recognize(self, path: Path) -> str:
        local_result: OcrResult | None = None
        local_error: DocumentError | None = None
        if self.local is not None:
            try:
                local_result = self.local.recognize_detailed(path)
            except DocumentError as exc:
                local_error = exc
        good = (
            local_result is not None
            and len(local_result.text.strip()) >= self.min_chars
            and (local_result.confidence is None or local_result.confidence >= self.min_confidence)
        )
        if good or self.vision is None:
            if local_result is None:
                if local_error is not None:
                    raise local_error
                raise DocumentError(
                    f"{Path(path).name}: no OCR engine available and no vision model"
                    " permitted for this document's data class"
                )
            self.last_engine = local_result.engine
            self.name = f"{local_result.engine}"
            return local_result.text
        # Escalation: the page goes to the vision model, page by page.
        texts: list[str] = []
        for image, media_type in page_images(path):
            text, _confidence = self.vision(image, media_type)
            texts.append(text)
        self.last_engine = "vision"
        self.name = "vision"
        log.info(
            "ocr escalated to vision model for %s (local: %s)",
            Path(path).name,
            "weak result" if local_result is not None else (local_error or "no engine"),
        )
        return "\n\n".join(t for t in texts if t).strip()


def _cache_path(path: Path) -> Path:
    return path.with_name(path.name + CACHE_SUFFIX)


def _cached(path: Path) -> ExtractedText | None:
    cache = _cache_path(path)
    if not cache.is_file():
        return None
    try:
        data = json.loads(cache.read_text(encoding="utf-8"))
        stat = path.stat()
        if data.get("size") != stat.st_size or data.get("mtime_ns") != stat.st_mtime_ns:
            return None
        return ExtractedText(
            text=str(data["text"]), page_count=int(data.get("page_count", 1)),
            method=str(data["method"]),
        )
    except (OSError, ValueError, KeyError, TypeError):
        return None


def _remember(path: Path, extracted: ExtractedText) -> None:
    """Best effort: a failing cache write never fails the extraction."""
    try:
        stat = path.stat()
        _cache_path(path).write_text(
            json.dumps(
                {
                    "size": stat.st_size,
                    "mtime_ns": stat.st_mtime_ns,
                    "method": extracted.method,
                    "page_count": extracted.page_count,
                    "text": extracted.text,
                },
                ensure_ascii=False,
            ),
            encoding="utf-8",
        )
    except OSError as exc:
        log.warning("cannot cache extraction for %s: %s", path.name, exc)


def cached_text(path: str | Path) -> ExtractedText | None:
    """The cached extraction for a file, if it is still valid."""
    return _cached(Path(path))


def is_media(path: str | Path) -> bool:
    suffix = Path(path).suffix.lower()
    return suffix in AUDIO_TYPES or suffix in VIDEO_TYPES


def media_type_of(path: str | Path) -> str | None:
    suffix = Path(path).suffix.lower()
    return IMAGE_TYPES.get(suffix) or AUDIO_TYPES.get(suffix) or VIDEO_TYPES.get(suffix)


def extract_text(
    path: str | Path,
    ocr: OcrEngine | None = None,
    *,
    transcriber: Transcriber | None = None,
    ffmpeg: Ffmpeg | None = None,
    describe: FrameDescriber | None = None,
) -> ExtractedText:
    """Extract text from a document.

    PDFs are read through their text layer; if the text layer is empty the
    configured OCR engine is asked (or a :class:`DocumentError` is raised
    by :class:`UnavailableOcr`). Images (photos, scans) always go through
    OCR. Audio is transcribed, video is transcribed from its audio track
    and - with a permitted ``describe`` - annotated with key frames
    (ADR-0030). HTML pages and office files (Word, Excel, PowerPoint,
    OpenDocument) are read with the standard library (ADR-0045).
    Anything else is treated as plain UTF-8 text. OCR and
    transcription results are cached next to the file.
    """
    path = Path(path)
    if not path.is_file():
        raise DocumentError(f"{path}: not a file")

    suffix = path.suffix.lower()
    if suffix in IMAGE_TYPES or is_media(path):
        cached = _cached(path)
        if cached is not None:
            return cached

    if suffix in IMAGE_TYPES:
        engine = ocr or UnavailableOcr()
        text = engine.recognize(path)
        result = ExtractedText(text=text, page_count=1, method=f"ocr:{engine.name}")
        _remember(path, result)
        return result

    if suffix in AUDIO_TYPES or suffix in VIDEO_TYPES:
        engine = transcriber or UnavailableTranscriber()
        try:
            if suffix in AUDIO_TYPES:
                transcript = engine.transcribe(path)
                text, method = transcript.with_timestamps(), f"transcript:{transcript.engine}"
            else:
                if ffmpeg is None:
                    raise DocumentError(f"{path.name}: ffmpeg is needed to read video")
                video = transcribe_video(path, engine, ffmpeg, describe)
                text = video.text
                method = f"transcript:{video.transcript.engine}" + (
                    "+vision" if video.frames else ""
                )
        except TranscriptionError as exc:
            raise DocumentError(str(exc)) from exc
        result = ExtractedText(text=text, page_count=1, method=method)
        _remember(path, result)
        return result

    if suffix in HTML_TYPES:
        page = html_page(path.read_bytes())
        text = (f"# {page.title}\n\n" if page.title else "") + page.text
        return ExtractedText(text=text, page_count=1, method="html")

    if suffix in OFFICE_TYPES:
        try:
            text = office_text(path)
        except FormatError as exc:
            raise DocumentError(str(exc)) from exc
        return ExtractedText(text=text, page_count=1, method=f"office:{suffix[1:]}")

    if suffix != ".pdf":
        try:
            return ExtractedText(
                text=path.read_text(encoding="utf-8"), page_count=1, method="plain_text"
            )
        except UnicodeDecodeError as exc:
            raise DocumentError(
                f"{path.name}: neither PDF, image, recording nor UTF-8 text"
            ) from exc

    try:
        with pdfplumber.open(path) as pdf:
            pages = [page.extract_text() or "" for page in pdf.pages]
    except Exception as exc:  # pdfplumber raises various internals
        raise DocumentError(f"{path.name}: cannot read PDF: {exc}") from exc

    result = ExtractedText(
        text="\n\n".join(pages).strip(), page_count=len(pages), method="text_layer"
    )
    if not result.is_empty:
        return result

    cached = _cached(path)
    if cached is not None:
        return cached
    engine = ocr or UnavailableOcr()
    result = ExtractedText(
        text=engine.recognize(path), page_count=result.page_count, method=f"ocr:{engine.name}"
    )
    _remember(path, result)
    return result


def create_pdf(path: str | Path, title: str, lines: list[str]) -> Path:
    """Write a simple text PDF (title plus paragraph lines) to ``path``."""
    path = Path(path)
    page = canvas.Canvas(str(path), pagesize=A4)
    _width, height = A4
    margin, leading = 20 * mm, 6 * mm

    y = height - margin
    page.setFont("Helvetica-Bold", 14)
    page.drawString(margin, y, title)
    y -= 2 * leading
    page.setFont("Helvetica", 10)
    from reportlab.lib.utils import simpleSplit

    for line in lines:
        # long lines wrap at the margin; an empty line stays a gap
        for part in simpleSplit(line, "Helvetica", 10, _width - 2 * margin) or [""]:
            if y < margin:
                page.showPage()
                page.setFont("Helvetica", 10)
                y = height - margin
            page.drawString(margin, y, part)
            y -= leading
    page.save()
    return path
